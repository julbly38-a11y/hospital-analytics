// Скорочені варіанти для показу в UI — лише для конкретних назв, що не
// вміщаються без переносу рядка в клінічному блоці (entry.html). Канонічна
// назва в lpz_departments (та всюди в інших місцях: госпіталізації, empl
// тощо) лишається повною, без змін. Спільний для /api/lpz-departments і
// /api/lpz-duty-doctors, щоб назви відділень збігались (потрібно для
// підсвітки лікар↔відділення на клієнті).
const DISPLAY_NAME_OVERRIDES = {
  'Стаціонарне відділення паліативної медичної допомоги': 'Паліативне відділення',
  'Відділення інтервенційної нейрохірургії та кардіології': 'Інтервенційне відділення',
}

export function displayDeptName(name) {
  return DISPLAY_NAME_OVERRIDES[name] || name
}
